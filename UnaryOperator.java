import java.util.Scanner;

public class UnaryOperator {

	public static void main(String[] args) {
		
		int a = 50;
		//Scanner sc=new Scanner(System.in);
		//POST INCREMENT
		a++;
		System.out.println(a);
		
		//POST DECREMENT
		a--;
		System.out.println(a);
		
		//PRE INCREMENT
		
		++a;
		System.out.println(a);
		
		//PRE DECREMENT
		
		--a;
		System.out.println(a);

	}

}
