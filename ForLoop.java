import java.util.ArrayList;
import java.util.List;

public class ForLoop {

	public static void main(String[] args) {
	
		List<Integer> numbers = new ArrayList<>();

        
        for (int i = 1; i <= 5; i++) {
            numbers.add(i);
        }
        System.out.println("Numbers in the ArrayList: " + numbers);
    }
}
		


	

